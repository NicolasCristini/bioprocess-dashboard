"""Write .streamlit/config.toml (native mode) from the design tokens in app/ui/tokens.py.

usage: python3 scripts/sync_theme.py [--check]     (--check: exit 1 if the file is out of date)
"""
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load_tokens():
    spec = importlib.util.spec_from_file_location("tokens", ROOT / "app" / "ui" / "tokens.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def toml_value(v):
    return json.dumps(v)  # strings, numbers, booleans and lists of them are valid TOML in JSON form


def render(native: bool = True) -> str:
    """native=True: .streamlit/config.toml for `streamlit run`; False: the copy mounted into the in-browser app."""
    theme = load_tokens().streamlit_theme()
    main = {k: v for k, v in theme.items() if "." not in k and k != "fontFaces"}
    side = {k.split(".", 1)[1]: v for k, v in theme.items() if k.startswith("sidebar.")}
    lines = ["# GENERATED by scripts/sync_theme.py from app/ui/tokens.py. Do not edit by hand."]
    if native:
        lines += ["# Native mode (uv run streamlit run app/Home.py): local only, no telemetry.",
                  "[server]", 'address = "127.0.0.1"', "port = 8501", "headless = true", "enableStaticServing = true", ""]
    lines += ["[browser]", "gatherUsageStats = false", "",
             "[client]", 'toolbarMode = "minimal"', "",
             "[theme]"]
    lines += [f"{k} = {toml_value(v)}" for k, v in main.items()]
    for face in theme["fontFaces"]:
        lines += ["", "[[theme.fontFaces]]"] + [f"{k} = {toml_value(v)}" for k, v in face.items()]
    lines += ["", "[theme.sidebar]"] + [f"{k} = {toml_value(v)}" for k, v in side.items()]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    target = ROOT / ".streamlit" / "config.toml"
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text() == text else 1)
    target.write_text(text)
    print(f"wrote {target}")
